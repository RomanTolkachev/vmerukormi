export function parameterHelp(template: FormulaTemplate, key: ParameterKey): ParameterHelp {
  switch (key) {
    case "AW": return { hint: "AW — текущая масса питомца в килограммах. В формулах роста используется вместе с ожидаемой взрослой массой IW." };
    case "IW": return { hint: template.growing
      ? "IW — ожидаемая масса питомца во взрослом возрасте, а не его масса сейчас. Отношение AW к IW показывает, насколько он приблизился к взрослой массе."
      : "IW — масса при целевой упитанности в килограммах. В этой формуле она используется вместо фактической массы питомца." };
    case "LACTATION_WEEK": return { hint: "Номер недели после родов, начиная с 1. Определяет автоматический L — поправку на этап лактации; при ручном L неделю можно не заполнять." };
    case "CHILDREN": return { hint: template.profile === "CAT_LACTATION"
      ? "Число котят в помёте. Определяет автоматический K; если K задан вручную, количество можно не заполнять."
      : "Число щенков в помёте. Определяет автоматические N и M; если оба заданы вручную, количество можно не заполнять." };
    case "K": return { hint: "Поправка на количество котят. Вместе с массой IW и множителем L определяет дополнительную энергию на лактацию.", rules: catRules.K };
    case "L": return { hint: "Множитель дополнительной энергии на лактацию, зависящий от недели после родов. Базовую часть энергии не меняет.", rules: template.profile === "CAT_LACTATION" ? catRules.L : dogRules.L };
    case "N": return { hint: "Число первых щенков помёта — автоматически не более 4. В формуле умножается на коэффициент первых щенков.", rules: dogRules.N };
    case "M": return { hint: "Число следующих щенков — с 5-го по 8-й. В формуле умножается на коэффициент следующих щенков.", rules: dogRules.M };
  }
}

export function coefficientHint(template: FormulaTemplate, key: string): string {
  const mass = template.growing ? "фактической массы AW" : "идеальной массы IW";
  const hints: Record<string, string> = {
    C1: `Множитель перед степенью ${mass}. Задаёт масштаб базовой части расчёта энергии.`,
    C2: `Степень, в которую возводится значение ${mass}. Определяет, как энергия зависит от массы; это не процент.`,
    ...(template.growing ? {
      C3: "Множитель роста. Умножает базовую энергию вместе с поправкой, зависящей от отношения текущей массы AW к взрослой IW.",
      C4: "Коэффициент при AW / IW внутри exp(−…). Определяет, как экспоненциальная поправка меняется по мере приближения к взрослой массе.",
      C5: "Число, которое вычитается из результата exp(−…) перед умножением на базовую энергию и множитель роста.",
    } : template.profile === "DOG_LACTATION" ? {
      C3: "Множитель для первых щенков N. Его вклад умножается на массу IW и поправку L и добавляется к базовой энергии.",
      C4: "Множитель для следующих щенков M. Его вклад умножается на массу IW и поправку L и добавляется к базовой энергии.",
    } : {
      C3: "Умножается на идеальную массу IW и добавляется к базовой энергии во второй фазе беременности.",
    }),
  };
  return hints[key];
}

